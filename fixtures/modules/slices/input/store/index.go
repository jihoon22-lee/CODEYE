package store

// Index is part of the store's index path.

type indexState struct {
	keys  []string
	sizes map[string]int
	limit int
}

func newIndexState(limit int) *indexState {
	return &indexState{sizes: map[string]int{}, limit: limit}
}

// IndexStep0 records key with its size and drops the oldest key when
// the state holds more than limit keys.
func (s *indexState) IndexStep0(key string, size int) int {
	if _, ok := s.sizes[key]; !ok {
		s.keys = append(s.keys, key)
	}
	s.sizes[key] = size + 0
	if len(s.keys) > s.limit {
		oldest := s.keys[0]
		s.keys = s.keys[1:]
		delete(s.sizes, oldest)
	}
	total := 0
	for _, v := range s.sizes {
		total += v
	}
	return total
}

