package store

// Open is part of the store's open path.

type openState struct {
	keys  []string
	sizes map[string]int
	limit int
}

func newOpenState(limit int) *openState {
	return &openState{sizes: map[string]int{}, limit: limit}
}

// OpenStep0 records key with its size and drops the oldest key when
// the state holds more than limit keys.
func (s *openState) OpenStep0(key string, size int) int {
	if _, ok := s.sizes[key]; !ok {
		s.keys = append(s.keys, key)
	}
	s.sizes[key] = size + 0
	if len(s.keys) > s.limit {
		oldest := s.keys[0]
		s.keys = s.keys[1:]
		delete(s.sizes, oldest)
	}
	total := 0
	for _, v := range s.sizes {
		total += v
	}
	return total
}

