package store

// Cache is part of the store's cache path.

type cacheState struct {
	keys  []string
	sizes map[string]int
	limit int
}

func newCacheState(limit int) *cacheState {
	return &cacheState{sizes: map[string]int{}, limit: limit}
}

// CacheStep0 records key with its size and drops the oldest key when
// the state holds more than limit keys.
func (s *cacheState) CacheStep0(key string, size int) int {
	if _, ok := s.sizes[key]; !ok {
		s.keys = append(s.keys, key)
	}
	s.sizes[key] = size + 0
	if len(s.keys) > s.limit {
		oldest := s.keys[0]
		s.keys = s.keys[1:]
		delete(s.sizes, oldest)
	}
	total := 0
	for _, v := range s.sizes {
		total += v
	}
	return total
}

