package store

// Scan is part of the store's scan path.

type scanState struct {
	keys  []string
	sizes map[string]int
	limit int
}

func newScanState(limit int) *scanState {
	return &scanState{sizes: map[string]int{}, limit: limit}
}

// ScanStep0 records key with its size and drops the oldest key when
// the state holds more than limit keys.
func (s *scanState) ScanStep0(key string, size int) int {
	if _, ok := s.sizes[key]; !ok {
		s.keys = append(s.keys, key)
	}
	s.sizes[key] = size + 0
	if len(s.keys) > s.limit {
		oldest := s.keys[0]
		s.keys = s.keys[1:]
		delete(s.sizes, oldest)
	}
	total := 0
	for _, v := range s.sizes {
		total += v
	}
	return total
}

