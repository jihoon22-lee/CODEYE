func TestContractFollowupFindsFreshGoDecisionCallers(t *testing.T) {
	const definition = `package app
func prepare[T any](value T) *T {
	return &value
}
`
	const caller = `package app
func load() string {
	if prepared := prepare[string]("fresh"); prepared != nil {
		return *prepared
	}
	return "default"
}
`
	for _, test := range []struct {
		name, callerPath, callerSource, declarationPath string
		pr, withheld, staleDefinition, staleCall        bool
		want                                            bool
	}{
		{name: "guard and result", callerSource: caller, want: true},
		{name: "same-file call", callerPath: "app/prepare.go", callerSource: strings.TrimPrefix(caller, "package app\n"), want: true},
		{name: "shadow", callerSource: `package app
func load(prepare func(string) string) string { return prepare("different") }
`},
		{name: "local type conversion", callerSource: `package app
func load() string { type prepare string; return string(prepare("different")) }
`},
		{name: "qualified selector", callerSource: `package app
func load(source any) string { return source.prepare("different") }
`},
		{name: "only logs", callerSource: `package app
func load() string { println(prepare("different")); return "default" }
`},
		{name: "condition independent of call", callerSource: `package app
func load() string { if value := prepare("different"); true { return *value }; return "default" }
`},
		{name: "same package name different directory", callerPath: "other/load.go", callerSource: caller},
		{name: "different package", callerSource: strings.Replace(caller, "package app", "package other", 1)},
		{name: "external dot import", callerSource: strings.Replace(caller, "package app", "package app\nimport . \"other\"", 1)},
		{name: "outside PR change", callerSource: caller, pr: true},
		{name: "test", callerPath: "app/load_test.go", callerSource: caller},
		{name: "generated", callerSource: "// Code generated by example. DO NOT EDIT.\n" + caller},
		{name: "withheld", callerSource: caller, withheld: true},
		{name: "platform suffix", declarationPath: "app/prepare_windows.go", callerSource: caller},
		{name: "stale definition", callerSource: caller, staleDefinition: true},
		{name: "stale call and outcome", callerSource: caller, staleCall: true},
	} {
		t.Run(test.name, func(t *testing.T) {
			decl, use := test.declarationPath, test.callerPath
			if decl == "" {
				decl = "app/prepare.go"
			}
			if use == "" {
				use = "app/load.go"
			}
			tree := map[string]string{decl: definition}
			tree[use] += test.callerSource
			j := treeJob(t, tree)
			if test.pr {
				j.PullRequest = &domain.PullRequestJob{Changed: []string{decl}}
			}
			s := &roleStage{ctx: t.Context(), j: j}
			if test.withheld {
				s.screen.withheld = map[string]bool{use: true}
			}
			files := s.entries()
			x := record.Excerpt{Path: decl, Kind: "code", SHA256: files[decl].SHA256, Start: 2, End: 4}
			var overview []record.Excerpt
			if test.staleDefinition {
				overview = append(overview, x)
			}
			if test.staleCall {
				// The surrounding wrapper and fallback still have unread lines.
				overview = append(overview, record.Excerpt{Path: use, Kind: "code", SHA256: files[use].SHA256, Start: 3, End: 4})
			}
			out, err := s.contractCallerExcerpts("app", []record.Excerpt{x}, overview)
			if err != nil || (len(out) > 0) != test.want {
				t.Fatalf("decision windows %+v: %v", out, err)
			}
			if test.want && (len(out) != 1 || out[0].Path != use || out[0].Origin != "caller" || out[0].Symbol != "prepare" ||
				!strings.Contains(out[0].Text, `prepared := prepare[string]("fresh")`) || !strings.Contains(out[0].Text, "return *prepared")) {
				t.Fatalf("decision or outcome missing: %+v", out)
			}
		})
	}

	// A duplicate package-level binding is ambiguous even if it parses on
	// its own. Additional log or test windows cannot substitute for the call.
	j := treeJob(t, map[string]string{
		"app/prepare.go": definition,
		"app/load.go":    caller,
		"app/other.go":   "package app\nvar prepare = func(value string) *string { return &value }\n",
	})
	s := &roleStage{ctx: t.Context(), j: j}
	e := s.entries()["app/prepare.go"]
	out, err := s.contractCallerExcerpts("app", []record.Excerpt{{Path: e.Path, Kind: "code", SHA256: e.SHA256, Start: 2, End: 4}}, nil)
	if err != nil || len(out) != 0 {
		t.Fatalf("ambiguous package binding: %+v, %v", out, err)
	}
}

func TestContractFollowupSendsGoCallerAsCitableEvidence(t *testing.T) {
	const name = "svc/b/policy.go"
	const source = `package b
func currentPolicy(enabled bool) *bool {
	if enabled { return &enabled }
	return nil
}

func choosePolicy(enabled bool) bool {
	if override := currentPolicy(enabled); override != nil {
		return *override
	}
	return false
}
`
	j := contractExampleJob(t, func(root string) { writeFile(t, root, name, source) })
	contractExampleInput(t, j)
	doc, inv := readRecord(t, j, record.StageDocuments), readRecord(t, j, record.StageInvestigate)
	doc.Conflicts = nil
	if _, err := persistRecord(j, doc); err != nil {
		t.Fatal(err)
	}
	for i, up := range inv.Upstream {
		if up.Source == "review.documents" {
			inv.Upstream[i].SHA256 = digestOf(mustRead(t, recordPath(j, record.StageDocuments)))
		}
	}
	e := (&roleStage{j: j}).entries()[name]
	inv.ContractProbe.Candidates = []record.ContractLocation{{
		ID: record.ContractLocationID(j.Snapshot.Digest, e.Path, e.SHA256, 2, 5), Path: e.Path, SHA256: e.SHA256,
		Start: 2, End: 5, Kind: "code", Symbol: "currentPolicy",
	}}
	inv.ContractProbe.Literals = nil
	if _, err := persistRecord(j, inv); err != nil {
		t.Fatal(err)
	}
	var callerID string
	f := &scriptedCaller{script: map[string]func(int, opencode.Request) opencode.Reply{
		record.StageContract: func(_ int, q opencode.Request) opencode.Reply {
			in := decodeAs[contractReviewInput](t, q)
			for _, x := range in.Scope.Excerpts {
				if x.Path == e.Path && x.Origin == "caller" && strings.Contains(x.Text, "return *override") {
					callerID = x.ID
				}
			}
			if callerID == "" {
				t.Fatalf("missing runtime caller in final request: %+v", in.Scope.Excerpts)
			}
			comparison := in.Prior
			comparison.CodeEvidenceIDs = []string{callerID}
			comparison.Reason = "호출자가 설정을 받았을 때 반환하는 값은 확인했다. 원래 문서 조건은 미확인이다."
			return asJSON(map[string]any{"contract_comparisons": []record.ContractComparison{comparison}})
		},
	}}
	h := Handler{Static: vetStub{}, Caller: f}
	res := h.Run(t.Context(), j, analysis.TaskSpec{Key: record.TaskContract}, nil)
	if res.Status != domain.TaskSucceeded || f.calls(record.StageContract) != 1 {
		t.Fatalf("final contract result %+v, calls %d", res, f.calls(record.StageContract))
	}
	final := readRecord(t, j, record.StageContract)
	if len(final.ContractComparisons) != 1 || final.ContractComparisons[0].Status != "unknown" ||
		len(final.ContractComparisons[0].CodeEvidenceIDs) != 1 || final.ContractComparisons[0].CodeEvidenceIDs[0] != callerID ||
		!record.ValidateContractFollowup(final, doc, inv) {
		t.Fatalf("final comparison did not preserve its original judgment and caller lineage: %+v", final.ContractComparisons)
	}
}

func TestContractFollowupTracesSelectedGoFunctionBodyAndGuardCallee(t *testing.T) {
	const workerPath = "app/collector.go"
	const edgePath = "app/entry.go"
	intro := "package app\nfunc collect(items []bool) int {\n" + strings.Repeat("\t// Keep the function declaration outside the selected window.\n", 25)
	body := `	count := 0
	for _, skip := range items {
		if shouldSkip(skip) {
			continue
		}
		count++
	}
	return count
}
`
	entry := `package app
func shouldSkip(skip bool) bool {
	return skip
}

func Load(items []bool) int {
	count := collect(items)
	if count == 0 {
		return -1
	}
	return count
}
`
	j := treeJob(t, map[string]string{workerPath: intro + body, edgePath: entry})
	s := &roleStage{ctx: t.Context(), j: j}
	file := s.entries()[workerPath]
	start := strings.Count(intro, "\n") + 1
	selected := record.Excerpt{Path: workerPath, Kind: "code", SHA256: file.SHA256, Start: start, End: start + 7}
	out, err := s.contractCallerExcerpts("app", []record.Excerpt{selected}, nil)
	if err != nil || len(out) != 2 {
		t.Fatalf("around a fresh function body got %+v: %v", out, err)
	}
	caller, callee := out[0], out[1]
	if caller.Path != edgePath || caller.Origin != "caller" || caller.Symbol != "collect" || !strings.Contains(caller.Text, "count := collect(items)") ||
		!strings.Contains(caller.Text, "return -1") || callee.Path != edgePath || callee.Origin != "context" || !strings.Contains(callee.Text, "return skip") {
		t.Fatalf("actual guard, public caller or their behavior was omitted: %+v", out)
	}
}
