const greenhouseHTTP = `package greenhouse
import "net/http"
func routes(m *http.ServeMux) {
	m.HandleFunc("POST /greenhouses/{id}/refresh", refresh)
	m.HandleFunc("GET /greenhouses/{id}", read)
}
func refresh(w http.ResponseWriter, r *http.Request) { w.WriteHeader(http.StatusNoContent) }
func read(w http.ResponseWriter, r *http.Request) { w.WriteHeader(http.StatusOK) }
`

const greenhouseTest = `package greenhouse
import (
	"net/http"
	ht "net/http/httptest"
	"testing"
)
func request(verb, route string) *http.Request {
	return ht.NewRequest(verb, route, nil)
}
func TestRefreshAndRead(t *testing.T) {
	srv := http.NewServeMux()
	routes(srv)
	id := "north"
	{
		req := request(http.MethodPost, ` + "`/greenhouses/`" + ` + id + "/refresh")
		rec := ht.NewRecorder()
		srv.ServeHTTP(rec, req)
		if got := rec.Code; got != http.StatusNoContent { t.Errorf("unexpected status %d", got) }
	}
	{
		req := ht.NewRequest("GET", ` + "`/greenhouses/north`" + `, nil)
		rec := ht.NewRecorder()
		srv.ServeHTTP(rec, req)
		res := rec.Result()
		if got, want := res.StatusCode, 200; got != want { t.Fatalf("unexpected status %d", got) }
		if got := rec.Body.String(); got != "ready" { t.Errorf("unexpected body: %q", got) }
	}
}
`

func TestGoHTTPWorkflowUsesOneReadAfterChangeTestWindow(t *testing.T) {
	tree := map[string]string{"greenhouse/routes.go": greenhouseHTTP, "greenhouse/change_test.go": greenhouseTest}
	s := roleStage{ctx: t.Context(), j: treeJob(t, tree)}
	catalog, err := s.workflowRoutes()
	if err != nil || len(catalog) != 2 {
		t.Fatalf("catalog %v: %v", catalog, err)
	}
	out, err := s.workflowRouteTests(catalog, catalog)
	if err != nil || len(out) != 2 || out[0].ID == "" || out[0].ID != out[1].ID {
		t.Fatalf("single sequence window expected: %+v, %v", out, err)
	}
	found := out[0]
	if found.Path != "greenhouse/change_test.go" || found.Kind != "test" || found.End-found.Start >= httpAssertionLines ||
		!strings.Contains(found.Text, "request(http.MethodPost") || !strings.Contains(found.Text, "ht.NewRequest(\"GET\"") ||
		!strings.Contains(found.Text, "res.StatusCode") || !strings.Contains(found.Text, `rec.Body.String()`) {
		t.Fatalf("test window does not contain both requests and assertions: %+v", found)
	}
	read, err := s.withText([]record.Excerpt{found})
	if err != nil || len(read) != 1 || read[0] != found {
		t.Fatalf("test window did not verify against snapshot: %+v, %v", read, err)
	}
}

func TestGoHTTPWorkflowTestRequiresMatchingExecutedRequestAndAssertion(t *testing.T) {
	for _, tc := range []struct {
		name, old, replacement string
		setup                  func(*roleStage)
		generated, duplicate   bool
	}{
		{name: "different method", old: "request(http.MethodPost", replacement: "request(http.MethodPut"},
		{name: "different route segment", old: ` + id + "/refresh"`, replacement: ` + id + "/refreshing"`},
		{name: "ignored assertion", old: `t.Errorf("unexpected status %d", got)`, replacement: `t.Logf("unexpected status %d", got)`},
		{name: "request constructed but never served", old: "srv.ServeHTTP(rec, req)", replacement: "_ = req"},
		{name: "ambiguous recorder reuse", old: "srv.ServeHTTP(rec, req)", replacement: "srv.ServeHTTP(rec, req); srv.ServeHTTP(rec, req)"},
		{name: "recorder status prefilled", old: "srv.ServeHTTP(rec, req)", replacement: "rec.WriteHeader(http.StatusNoContent); srv.ServeHTTP(rec, req)"},
		{name: "subsequent request path overwrite", old: "srv.ServeHTTP(rec, req)", replacement: `req.URL.Path = "/different"; srv.ServeHTTP(rec, req)`},
		{name: "opaque helper", old: "return ht.NewRequest(verb, route, nil)", replacement: `return &http.Request{Method: verb}`},
		{name: "concrete status on different value", old: "got := rec.Code", replacement: "got := 200"},
		{name: "generated test", generated: true},
		{name: "duplicate registration", duplicate: true},
		{name: "withheld test", setup: func(s *roleStage) { s.screen.withheld = map[string]bool{"greenhouse/change_test.go": true} }},
		{name: "unchanged PR test", setup: func(s *roleStage) {
			s.j.PullRequest = &domain.PullRequestJob{Changed: []string{"greenhouse/routes.go"}}
		}},
		{name: "out-of-scope test", setup: func(s *roleStage) { s.j.Scope = domain.Scope{Kind: "paths", Paths: []string{"greenhouse/routes.go"}} }},
	} {
		t.Run(tc.name, func(t *testing.T) {
			test := greenhouseTest
			if tc.old != "" {
				test = strings.Replace(test, tc.old, tc.replacement, 1)
			}
			if tc.generated {
				test = "// Code generated by example. DO NOT EDIT.\n" + test
			}
			production := greenhouseHTTP
			if tc.duplicate {
				production += `
func otherRouter(m *http.ServeMux) { m.HandleFunc("POST /greenhouses/north/refresh", read) }
`
			}
			tree := map[string]string{"greenhouse/routes.go": production, "greenhouse/change_test.go": test}
			s := roleStage{ctx: t.Context(), j: treeJob(t, tree)}
			if tc.setup != nil {
				tc.setup(&s)
			}
			catalog, err := s.workflowRoutes()
			if err != nil || len(catalog) < 2 || catalog[0].Method != "POST" {
				t.Fatalf("catalog %v: %v", catalog, err)
			}
			out, err := s.workflowRouteTests(catalog[:1], catalog)
			if err != nil || len(out) != 1 || out[0].ID != "" {
				t.Fatalf("unsupported association: %+v, %v", out, err)
			}
		})
	}
}

func TestGoHTTPWorkflowTestMatchesOnlyConcretePathShape(t *testing.T) {
	for _, tc := range []struct {
		pattern, kind, target string
		want                  bool
	}{
		{pattern: "/rooms/{id}", target: "/rooms/lobby", want: true},
		{pattern: "/rooms/{id}", target: "/rooms/lobby/open"},
		{pattern: "/rooms/{id}", target: "/rooms/"},
		{pattern: "/rooms/{id}", target: "/rooms/lobby/"},
		{pattern: "/rooms/-{id}", target: "/rooms/-lobby", want: true},
		{pattern: "/rooms/-{id}", kind: "prefix", target: "/rooms/-lobby/lights", want: true},
		{pattern: "/rooms/{id:[a-z]+}", target: "/rooms/lobby"},
		{pattern: "/assets/", kind: "prefix", target: "/assets/main.css", want: true},
		{pattern: "/assets", kind: "prefix", target: "/assetsother/main.css"},
		{pattern: "rooms/{id}", target: "/v1/rooms/lobby"},
	} {
		if got := testRouteMatches(workflowRoute{Path: tc.pattern, PatternKind: tc.kind}, tc.target); got != tc.want {
			t.Errorf("pattern %q kind %q target %q: %v", tc.pattern, tc.kind, tc.target, got)
		}
	}
}
