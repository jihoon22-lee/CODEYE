// The secondary path rule: directory segments only (the file name never
// matches), any depth, case-insensitive, tests/data as two directories, and
// build/dist do not apply to Go files.
func TestSecondaryRuleMatch(t *testing.T) {
	r := DefaultSecondary
	if !r.Valid() {
		t.Fatal("default rule invalid")
	}
	for p, want := range map[string]string{
		"fixtures/rust/clean/src/lib.rs": "fixtures",
		"internal/x/testdata/a.go":       "testdata",
		"web/src/__snapshots__/a.ts":     "__snapshots__",
		"pkg/tests/data/case.py":         "tests/data",
		"pkg/tests/test_x.py":            "",
		"src/Generated/api.ts":           "generated",
		"internal/build/b.go":            "",
		"web/build/out.js":               "build",
		"tools/dist/x.py":                "dist",
		"cmd/gen/main.go":                "gen",
		"examples.go":                    "",
		"internal/examples/a.go":         "examples",
		"main.go":                        "",
	} {
		if got := r.Match(p); got != want {
			t.Errorf("%s: %q, want %q", p, got, want)
		}
	}
	for m, want := range map[string]string{
		"go:.": ClassPrimary, "go:fixtures/modules/input": ClassSecondary, "rust:fixtures/rust/clean": ClassSecondary,
		"go:build/tool": ClassPrimary, "javascript:dist/app": ClassSecondary, "python:scripts": ClassPrimary, "cpp:third_party/zlib": ClassSecondary,
	} {
		if got := r.ModuleClass(m); got != want {
			t.Errorf("%s: %s, want %s", m, got, want)
		}
	}
	for _, bad := range []SecondaryRule{{Segments: []string{}, NotForGo: []string{}}, {Segments: []string{"a"}}, {Segments: []string{"A"}, NotForGo: []string{}},
		{Segments: []string{"a", "a"}, NotForGo: []string{}}, {Segments: []string{"a/"}, NotForGo: []string{}}, {Segments: []string{"a"}, NotForGo: []string{"b"}}} {
		if bad.Valid() {
			t.Errorf("rule %+v accepted", bad)
		}
	}
}

func TestGeneratedHeaderAndSeverity(t *testing.T) {
	for head, want := range map[string]bool{
		"// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage x\n":            true,
		"/* eslint-disable */\n// @generated by tool\nexport const x = 1\n":          true,
		"package x\n\n// DO NOT EDIT this by hand\n":                                 false,
		"package x\n" + "\n\n\n\n\n\n\n\n\n\n" + "// Code generated x DO NOT EDIT\n": false,
		"# Code generated by gen.py. DO NOT EDIT.\nimport os\n":                      true,
		"// Code generated\n// DO NOT EDIT\n":                                        false,
		strings.Repeat("\n", 9) + "// @generated":                                    true,
		strings.Repeat("\n", 10) + "// @generated":                                   false,
	} {
		if got := GeneratedHeader([]byte(head)); got != want {
			t.Errorf("%q: %v", head, got)
		}
	}
	s := func(v string) *string { return &v }
	for raw, want := range map[*string]int{nil: 1, s("error"): 3, s("HIGH"): 3, s("warning"): 2, s("MEDIUM"): 2, s("LOW"): 1, s("info"): 1, s("ignored"): 0, s("convention"): 1} {
		if got := SeverityRank(raw); got != want {
			t.Errorf("%v: %d, want %d", raw, got, want)
		}
	}
}
