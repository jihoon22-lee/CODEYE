const generatedQuotes = "// Code generated by fixture. DO NOT EDIT.\n\npackage quotes\n\n"

func TestDocumentedGoWrappersReachImplementationAndKeepScopeLedger(t *testing.T) {
	const usage = "quotes/README.md"
	const wrapper = "quotes/public.go"
	const render = "quotes/render.go"
	const calculator = "quotes/rules.go"
	const check = "quotes/product_test.go"
	files := map[string]string{
		"go.mod": "module example.org/product\n\ngo 1.23\n",
		usage:    "# Quoting\n\n    quotes.Render(\"draft\") // preview\n    quotes.Estimate(0) // no units\n",
		wrapper: generatedQuotes + "func Render(mode string) string {\n\tresult, _ := format(mode)\n\treturn result\n}\n" +
			"func InternalGenerated() int { return 4 }\n" +
			"func Estimate(units int) int {\n\treturn estimate(units)\n}\n",
		render: "package quotes\n" + strings.Repeat("// setup\n", 62) + "func format(mode string) (string, error) {\n" +
			"switch mode {\ncase \"ready\":\nreturn \"issued\", nil\n" + strings.Repeat("// Other cases\n", 25) +
			"case \"draft\":\nreturn \"preview\", nil\ndefault:\nreturn mode, nil\n}\n}\n",
		calculator: "package quotes\n" + strings.Repeat("// setup\n", 61) +
			"func estimate(units int) int { return fromCount[int](units, unchanged[int]) }\n" +
			"func unchanged[T ~int](n T) T { return n }\n" +
			strings.Repeat("// another section\n", 24) +
			"func fromCount[T ~int](n T, callback func(T) T) T {\nif n == 0 {\nreturn 0\n}\nreturn callback(n)\n}\n",
		check: "package quotes\nimport \"testing\"\n" + strings.Repeat("// other cases\n", 70) +
			"func TestPreview(t *testing.T) {\nif Render(\"draft\") != \"preview\" {\nt.Fatal(\"expected preview\")\n}\n}\n",
	}
	for i := range 12 {
		files[fmt.Sprintf("quotes/a%02d.go", i)] = "package quotes\n" + strings.Repeat("// setup\n", 63)
	}
	j := treeJob(t, files)
	var sent []record.Excerpt
	script := maxScript(t)
	script["documents"] = func(_ int, q opencode.Request) opencode.Reply {
		in := decodeAs[docsInput](t, q)
		d := in.Documents[slices.IndexFunc(in.Documents, func(e docInput) bool { return e.Path == usage })]
		return asJSON(docsOutput{
			Contracts: []record.Contract{{Statement: "`Render(\"draft\")`는 미리보기를 반환하고 `Estimate(0)`은 0을 반환한다.",
				AppliesTo: "quotes", EvidenceIDs: []string{d.EvidenceID}}},
			Conflicts: []record.Conflict{}, Questions: []record.Question{}, InstructionNotes: []record.InstructionNote{},
		})
	}
	script["investigate"] = func(_ int, q opencode.Request) opencode.Reply {
		in := decodeAs[investigateInput](t, q)
		if !in.Scope.WholeRun {
			if len(in.Scope.DirectCalls) != 0 {
				t.Fatal("overview links were sent to a slice")
			}
			return asJSON(map[string]any{"candidates": []any{}})
		}
		sent = in.Scope.Excerpts
		catalog := catalogOf(sent)
		if len(sent) > roleMaxCodeFiles || len(in.Scope.DirectCalls) != 3 {
			t.Fatalf("unexpected overview: %+v", in.Scope)
		}
		var totalBytes, generatedBytes, generatedLines int
		generatedWindows := 0
		for _, x := range sent {
			totalBytes += record.JSONLen(x.Text)
			if x.Path == wrapper {
				generatedWindows++
				generatedBytes += record.JSONLen(x.Text)
				generatedLines += x.End - x.Start + 1
				if strings.Contains(x.Text, "InternalGenerated") {
					t.Fatalf("unrelated generated code was promoted: %+v", x)
				}
			}
		}
		if totalBytes > roleMaxCodeBytes || generatedWindows != 2 ||
			generatedBytes > roleMaxCodeFile || generatedLines > roleMaxCodeLines {
			t.Fatalf("invalid total or per-file budget: %+v", sent)
		}
		want := []struct{ caller, callee, text string }{
			{wrapper, render, "case \"draft\":\nreturn \"preview\", nil"},
			{wrapper, calculator, "return fromCount[int](units, unchanged[int])"},
			{calculator, calculator, "if n == 0 {\nreturn 0"},
		}
		var ids []string
		for i, link := range in.Scope.DirectCalls {
			from, to := catalog[link.CallerEvidenceID], catalog[link.CalleeEvidenceID]
			if from.Path != want[i].caller || to.Path != want[i].callee || to.Start <= 50 || !strings.Contains(to.Text, want[i].text) {
				t.Fatalf("incorrectly bound direct call: %+v, %+v, %+v", link, from, to)
			}
			ids = append(ids, to.ID)
		}
		if !slices.ContainsFunc(sent, func(x record.Excerpt) bool { return x.Path == check && x.Kind == "test" }) {
			t.Fatalf("related test displaced from overview: %+v", sent)
		}
		return asJSON(map[string]any{"candidates": []any{}, "contract_comparisons": []record.ContractComparison{{
			ContractIndex: 1, AppliesTo: "quotes", Status: "match", Reason: "미리보기와 빈 수량의 반환 조건이 문서와 같다.",
			DocumentEvidenceIDs: in.Documents.Contracts[0].EvidenceIDs, CodeEvidenceIDs: ids,
		}}})
	}
	_, results := runRoleSmall(t, j, langStub{eco: "go", path: render, line: 65, manifest: "go.mod"}, &scriptedCaller{script: script}, "1.27.4")
	if results[record.TaskScope].Status != domain.TaskSucceeded || results["review.investigate"].Status != domain.TaskSucceeded {
		t.Fatalf("review stages did not finish: %+v", results)
	}
	actual := readRecord(t, j, "investigate")
	if len(actual.ContractComparisons) != 1 {
		t.Fatalf("implementation citations were not accepted: %+v", actual)
	}
	b, err := os.ReadFile(scopePath(j))
	if err != nil {
		t.Fatal(err)
	}
	scope, err := record.DecodeScope(b, scopeExpect(j))
	if err != nil {
		t.Fatal(err)
	}
	generated := slices.IndexFunc(scope.Overview.Files, func(f record.ScopeFile) bool { return f.Path == wrapper })
	if generated < 0 {
		t.Fatalf("generated excerpt missing from scope: %+v", scope.Overview)
	}
	f := scope.Overview.Files[generated]
	var lines, bytes int
	for _, x := range sent {
		if x.Path == wrapper {
			lines += x.End - x.Start + 1
			bytes += record.JSONLen(x.Text)
		}
	}
	if f.Class != record.ClassSecondary || f.Secondary != record.ReasonGeneratedFile ||
		f.State != record.FileCoveredByOverview || f.PlannedLines != lines || f.PlannedBytes != bytes || f.TotalLines <= f.PlannedLines {
		t.Fatalf("generated classification or exposure mismatch: %+v", f)
	}
	unique := map[string]bool{}
	for _, x := range sent {
		unique[x.Path] = true
	}
	if len(scope.Overview.Offered) != len(unique) {
		t.Fatalf("multiple windows counted more than once: %+v", scope.Overview)
	}
}

func TestDocumentedGoWrappersRequireExactLocalUnambiguousSource(t *testing.T) {
	const safeWrapper = "func Render(mode string) string { return format(mode) }\n"
	const safeHelper = "package quotes\nfunc format(mode string) string { return mode + \"!\" }\n"
	for _, tc := range []struct {
		name, docs, statement, wrapper, helper, extra string
		dir                                           string
		withheld, pullRequest, pathScope              bool
	}{
		{name: "missing exact name in statement", statement: "RenderVerbose(\"draft\") 반환을 확인한다."},
		{name: "missing exact name in citation", docs: "quotes.RenderVerbose(\"draft\")"},
		{name: "foreign package qualification", docs: "foreign.Render(\"draft\")"},
		{name: "conflicting contract qualification", statement: "foreign.Render(\"draft\") 반환을 확인한다."},
		{name: "method receiver", wrapper: "type writer struct{}\nfunc (writer) Render(mode string) string { return format(mode) }\n"},
		{name: "method call", wrapper: "type writer struct{}\nfunc Render(mode string) string { return (writer{}).format(mode) }\n"},
		{name: "local shadow", wrapper: "func Render(format func(string) string, mode string) string { return format(mode) }\n"},
		{name: "modified input", wrapper: "func Render(mode string) string { return format(mode + \"!\") }\n"},
		{name: "generated helper", helper: generatedQuotes + "func format(mode string) string { return mode }\n"},
		{name: "different package", helper: strings.Replace(safeHelper, "package quotes", "package other", 1)},
		{name: "ambiguous name", extra: "//go:build custom\n\n" + safeHelper},
		{name: "non-forwarding generated body", wrapper: "func Render(mode string) string { return strings.ToUpper(mode) }\n"},
		{name: "unrelated generated declaration on the same line", wrapper: "func Unrelated() {}; " + safeWrapper},
		{name: "withheld implementation", withheld: true},
		{name: "PR", pullRequest: true},
		{name: "out of review scope", pathScope: true},
		{name: "secondary directory", dir: "generated/quotes"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := tc.dir
			if dir == "" {
				dir = "quotes"
			}
			docsPath, wrapperPath, helperPath := dir+"/README.md", dir+"/published.go", dir+"/product.go"
			docs := tc.docs
			if docs == "" {
				docs = "quotes.Render(\"draft\")"
			}
			statement := tc.statement
			if statement == "" {
				statement = "Render(\"draft\") 결과를 확인한다."
			}
			wrapper, helper := tc.wrapper, tc.helper
			if wrapper == "" {
				wrapper = safeWrapper
			}
			if helper == "" {
				helper = safeHelper
			}
			files := map[string]string{docsPath: docs, wrapperPath: generatedQuotes + wrapper, helperPath: helper}
			if tc.extra != "" {
				files[dir+"/alternate.go"] = tc.extra
			}
			j := treeJob(t, files)
			if tc.pullRequest {
				j.PullRequest = &domain.PullRequestJob{Changed: []string{wrapperPath, helperPath}}
			}
			if tc.pathScope {
				j.Scope = domain.Scope{Kind: "paths", Paths: []string{wrapperPath}}
			}
			s := &roleStage{h: Handler{Budget: smallBudget}, ctx: t.Context(), j: j, role: record.StageInvestigate}
			if tc.withheld {
				s.screen.withheld = map[string]bool{helperPath: true}
			}
			e := s.entries()[docsPath]
			id := record.ExcerptID(j.Snapshot.Digest, e.Path, e.SHA256, 1, 1)
			d := record.Record{
				Evidence:  []record.Excerpt{{ID: id, Path: e.Path, SHA256: e.SHA256, Start: 1, End: 1, Kind: "document"}},
				Contracts: []record.Contract{{Statement: statement, AppliesTo: dir, EvidenceIDs: []string{id}}},
			}
			code, links, _, err := s.codeCorpus(d)
			if err != nil || len(links.directCalls) > 0 {
				t.Fatalf("unexpected wrapper promotion: %+v, %+v, %v", code, links.directCalls, err)
			}
			if tc.withheld && slices.ContainsFunc(code, func(x record.Excerpt) bool { return x.Path == helperPath }) {
				t.Fatalf("withheld source was sent: %+v", code)
			}
		})
	}
}
