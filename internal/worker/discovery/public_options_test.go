const cliGoSource = `package main
import "flag"
func main() {
    zone := flag.String("report-zone", "UTC", "zone used when formatting a report")
    flag.Parse()
    _ = zone
}
`

func TestDiscoveryFindsExplicitCLIOptionsAndCheckedDefaults(t *testing.T) {
	tests := []struct{ path, source, sym, value, other string }{
		{"main.go", cliGoSource, "--report-zone", "UTC", ""},
		{"src/main/java/tool/App.java", `import picocli.CommandLine.Option;
class App implements Runnable {
    @Option(names = {"--retry-limit", "-r"}, defaultValue = "3")
    int retryLimit;
    public void run() {}
}`, "--retry-limit", "3", ""},
		{"cli.py", `import argparse
parser = argparse.ArgumentParser()
parser.add_argument("--mode-limit", default=4)
config = parser.parse_args()
`, "--mode-limit", "4", ""},
		{"cli.ts", `import { Command } from "commander";
const program = new Command();
program.option("--store-dir <dir>", "output target", "/tmp/output");
program.parse();
`, "--store-dir", "/tmp/output", ""},
		{"src/main.rs", `use clap::Parser;
#[derive(Parser)]
struct Args {
    #[arg(long = "report-zone", env = "REPORT_ZONE", default_value = "UTC")]
    zone: String,
}
fn main() { let opts = Args::parse(); }
`, "--report-zone", "UTC", "REPORT_ZONE"},
		{"main.c", `#include <getopt.h>
static struct option options[] = {
    {"color-mode", required_argument, 0, 'c'},
    {0, 0, 0, 0}
};
int main(int argc, char **argv) {
    return getopt_long(argc, argv, "c:", options, 0);
}
`, "--color-mode", "", ""},
	}
	for _, test := range tests {
		t.Run(test.path, func(t *testing.T) {
			files := map[string]string{test.path: test.source, "README.md": "Tool used to print summaries.\n", "docs/usage.md": "Run the print command for a summary.\n"}
			j := jobOf(t, files, domain.Scope{Kind: "full"})
			d := runDocs(t, j, Budget{})
			gaps := d.Documents.DocumentationGaps
			want := 1
			if test.other != "" {
				want++
			}
			if len(gaps) != want {
				t.Fatalf("%s: expected %d verified documentation gaps, got %+v", test.path, want, gaps)
			}
			g := gaps[0]
			if g.Kind != envdoc.DocGapOption || g.Symbol != test.sym || g.Default != test.value || g.Source.Path != test.path ||
				!slices.Equal(g.Searched, []string{"README.md", "docs/usage.md"}) || g.Source.StartLine < 1 || g.Source.EndLine > len(lines([]byte(test.source))) {
				t.Fatalf("unexpected scope or provenance: %+v", g)
			}
			if test.other != "" && (gaps[1].Symbol != test.other || gaps[1].Kind != envdoc.DocGapEnvironment) {
				t.Fatalf("missing explicit env registration: %+v", gaps)
			}
			if test.path == "main.go" {
				if destination := os.Getenv("CODEYE_DOC_GAPS_EXAMPLE"); destination != "" {
					b, err := json.MarshalIndent(d, "", "  ")
					if err != nil {
						t.Fatal(err)
					}
					if err := os.WriteFile(destination, append(b, '\n'), 0o644); err != nil {
						t.Fatal(err)
					}
				}
			}
		})
	}
}

func TestDiscoveryNeverClaimsIncompleteOrAmbiguousDocumentationGap(t *testing.T) {
	for _, tcase := range []struct {
		name   string
		edit   func(map[string]string)
		scope  domain.Scope
		budget Budget
	}{
		{name: "documented at end", edit: func(f map[string]string) {
			f["docs/usage.md"] = strings.Repeat("A different first page.\n", 150) + "Use `--report-zone` here.\n"
		}},
		{name: "documented without dashes", edit: func(f map[string]string) { f["README.md"] = "The report_zone option uses UTC.\n" }},
		{name: "unavailable guide", edit: func(f map[string]string) { f["docs/usage.md"] = strings.Repeat("A different page.\n", 128) }, budget: Budget{64, 32, 10}},
		{name: "inventory truncated", budget: Budget{128, 128, 1}},
		{name: "path scope with omitted guide", scope: domain.Scope{Kind: "paths", Paths: []string{"main.go", "docs"}}},
		{name: "expired code registration", edit: func(f map[string]string) { f["main.go"] = strings.Replace(cliGoSource, "flag.Parse()", "", 1) }},
		{name: "shadowed registration", edit: func(f map[string]string) {
			f["main.go"] = strings.Replace(cliGoSource, "zone :=", "flag := impl{}\n    zone :=", 1)
		}},
		{name: "generated code", edit: func(f map[string]string) {
			f["main.go"] = "// Code generated by template. DO NOT EDIT.\n" + cliGoSource
		}},
		{name: "secret-like guide", edit: func(f map[string]string) { f["docs/usage.md"] = "password = \"abcdef12345678\"\n" }},
	} {
		t.Run(tcase.name, func(t *testing.T) {
			files := map[string]string{"main.go": cliGoSource, "README.md": "Tool used to print summaries.\n", "docs/usage.md": "Run the print command for a summary.\n"}
			if tcase.edit != nil {
				tcase.edit(files)
			}
			j := jobOf(t, files, tcase.scope)
			d := runDocs(t, j, tcase.budget)
			if len(d.Documents.DocumentationGaps) != 0 {
				t.Fatalf("unexpected absence claim: %+v", d.Documents.DocumentationGaps)
			}
		})
	}
}

func TestDiscoverySkipsPrivateAndConditionalCLIOptions(t *testing.T) {
	for _, tc := range []struct{ name, path, content string }{
		{"go platform filename", "main_linux.go", cliGoSource},
		{"go replaced parser", "main.go", strings.Replace(cliGoSource, "flag.Parse()", "flag.CommandLine = flag.NewFlagSet(\"other\", 0)\n    flag.Parse()", 1)},
		{"java hidden option", "App.java", `import picocli.CommandLine.Option;
class App {
    @Option(names = {"--private-flag"}, hidden = true)
    boolean privateFlag;
}`},
		{"python never registered", "app.py", `import argparse
parser = argparse.ArgumentParser()
if False:
    parser.add_argument("--private-flag")
parser.parse_args()
`},
		{"python hidden help", "app.py", `import argparse
parser = argparse.ArgumentParser()
parser.add_argument("--private-flag", help=argparse.SUPPRESS)
parser.parse_args()
`},
		{"typescript never registered", "app.ts", `import { Command } from "commander";
const program = new Command();
if (false) program.option("--private-flag");
program.parse();
`},
		{"rust conditional field", "main.rs", `use clap::Parser;
#[derive(Parser)]
struct Args {
    #[cfg(feature = "internal")]
    #[arg(long = "private-flag")]
    flag: bool
}
fn main() { Args::parse(); }
`},
		{"rust hidden options", "main.rs", `use clap::Parser;
#[derive(Parser)]
struct Args {
    #[arg(long = "private-flag", hide = true)]
    flag: bool,
    #[arg(env = "INTERNAL_ZONE", hide_env = true)]
    zone: String
}
fn main() { Args::parse(); }
`},
		{"native shadowed table", "main.cpp", `#include <getopt.h>
static struct option options[] = {
    {"private-flag", required_argument, 0, 'p'},
    {0, 0, 0, 0}
};
int main(int argc, char **argv) {
    struct option options[] = {{0, 0, 0, 0}};
    return getopt_long(argc, argv, "p:", options, 0);
}
`},
		{"native conditional table", "main.c", `#include <getopt.h>
static struct option options[] = {
#ifdef INTERNAL
    {"private-flag", required_argument, 0, 'p'},
#endif
    {0, 0, 0, 0}
};
int main(int argc, char **argv) {
    return getopt_long(argc, argv, "p:", options, 0);
}
`},
	} {
		t.Run(tc.name, func(t *testing.T) {
			j := jobOf(t, map[string]string{tc.path: tc.content, "README.md": "Read the CLI guide.\n"}, domain.Scope{Kind: "full"})
			if gaps := runDocs(t, j, Budget{}).Documents.DocumentationGaps; len(gaps) != 0 {
				t.Fatalf("unexpected gap for non-public registration: %+v", gaps)
			}
		})
	}
}

func TestDiscoveryRejectsUnverifiedSearchScope(t *testing.T) {
	j := jobOf(t, map[string]string{"main.go": cliGoSource, "README.md": "Read this guide.\n", "docs/usage.md": "Run the printer.\n"}, domain.Scope{Kind: "full"})
	d := runDocs(t, j, Budget{})
	if len(d.Documents.DocumentationGaps) != 1 {
		t.Fatal(d.Documents.DocumentationGaps)
	}
	d.Documents.DocumentationGaps[0].Searched = []string{"README.md"}
	b, err := json.Marshal(d)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := envdoc.Decode(b, input(j).Expect(envdoc.KindDocuments)); err == nil {
		t.Fatal("accepted shortened search scope")
	}
}
